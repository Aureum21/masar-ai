from sqlalchemy import Column,String,Integer,DateTime,JSON,Numeric,Boolean,ForeignKey,UniqueConstraint,Index
from database import Base

class Receipt(Base):
    __tablename__='travel_receipts'
    id=Column(String(32),primary_key=True)
    user_id=Column(Integer,ForeignKey('users.id',ondelete='CASCADE'),nullable=False,index=True)
    trip_id=Column(Integer,ForeignKey('trips.id',ondelete='SET NULL'),nullable=True,index=True)
    idempotency_key=Column(String(100),nullable=False)
    request_hash=Column(String(64),nullable=False)
    image_sha=Column(String(64),nullable=True)
    storage=Column(JSON,nullable=True)
    file_name=Column(String(180),nullable=True)
    is_demo=Column(Boolean,nullable=False,default=False)
    state=Column(String(20),nullable=False,default='uploading')
    merchant_name=Column(String(250),nullable=True)
    purchase_date=Column(String(10),nullable=True)
    currency=Column(String(3),nullable=True)
    total_amount=Column(Numeric(12,2),nullable=True)
    vat_amount=Column(Numeric(12,2),nullable=True)
    estimated_refund=Column(Numeric(12,2),nullable=True)
    category=Column(String(30),nullable=True)
    is_service=Column(Boolean,nullable=True)
    has_planet_tag=Column(Boolean,nullable=True)
    assessment_status=Column(String(30),nullable=False,default='needs_review')
    assessment=Column(JSON,nullable=False,default=dict)
    extracted_fields=Column(JSON,nullable=False,default=dict)
    corrections=Column(JSON,nullable=False,default=list)
    policy_version=Column(String(50),nullable=True)
    feedback=Column(String(500),nullable=True)
    revision=Column(Integer,nullable=False,default=1)
    attempts=Column(Integer,nullable=False,default=0)
    lease_token=Column(String(32),nullable=True)
    lease_until=Column(DateTime(timezone=True),nullable=True)
    created_at=Column(DateTime(timezone=True),nullable=False)
    updated_at=Column(DateTime(timezone=True),nullable=False)
    deleted_at=Column(DateTime(timezone=True),nullable=True)
    acknowledged_version=Column(String(50),nullable=False)
    __table_args__=(UniqueConstraint('user_id','idempotency_key',name='uq_receipt_request'),UniqueConstraint('user_id','image_sha',name='uq_receipt_photo'),Index('ix_receipt_jobs','state','lease_until','created_at'))
